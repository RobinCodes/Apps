#!/usr/bin/env python3
"""Copy the house style into every app, and check it is still there.

    python3 house/sync.py            copy into every app that is missing or stale
    python3 house/sync.py --check    say which are stale, change nothing
    python3 house/sync.py --list     the files and where each one goes

Three files travel to every app: `theme.py`, the palettes; `housestyle.py`, the
sheet and the two widgets CSS cannot draw; and `updater.py`, which keeps each
app current with the checkout it runs from. Three more travel only to the apps
that join the second brain: `brain.py` (the Order's layout, links and inbox),
`cards.py` (cards written in notes, and the review log) and `fsrs.py` (the
scheduler). They are vendored rather than imported, because
each app in this repository is a folder you can copy to another machine and run
on its own — `updater.py` has been vendored that way since the beginning, and
this only puts the copying under something that checks. The cost is that nine
copies can drift, so this is the thing that stops them: it copies byte for
byte, and `--check` is wired into `run-tests.py` so a drift fails the suite
rather than being noticed a month later when one app's Porcelain is a different
Porcelain from the rest.

Lyndon Browser is C and has no Python package, so it gets `src/house-themes.h`
instead: the same palettes, written out as a C table its `apply_style` emits
`@define-color` from. Generated from the same `theme.py`, so the browser's
Porcelain cannot drift from everything else's either.
"""

from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# The canonical files, and the apps they belong in. `updater.py` has been
# vendored like this since before `house/` existed and was kept in step by
# hand; it is listed here now so that it cannot drift either.
FILES = ("theme.py", "housestyle.py", "updater.py")

PACKAGES = {
    "Claude Program": "claudedesk",
    "Fathom": "fathom",
    "Git Manager": "gitmanager",
    "Hermione": "hermione",
    "LaRenderer": "larenderer",
    "Notedown": "notedown",
    "Terminal": "prism",
    "The Eye": "theeye",
}

# The second brain: where things are, the cards and the scheduler. Only the
# apps that read or write the brain get these — a disk scanner has no use for
# a spaced-repetition scheduler, and an unused copy is still a copy to drift.
BRAIN_FILES = ("brain.py", "cards.py", "fsrs.py")
BRAIN_APPS = ("Hermione", "Notedown", "The Eye")

# The C app, which takes the palettes as a generated header instead.
LYNDON_HEADER = os.path.join("Lyndon Browser", "src", "house-themes.h")


def targets():
    """Every (source, destination) pair, as absolute paths."""
    for app, package in sorted(PACKAGES.items()):
        names = FILES + (BRAIN_FILES if app in BRAIN_APPS else ())
        for name in names:
            yield (os.path.join(HERE, name),
                   os.path.join(ROOT, app, package, name))


def read(path):
    try:
        with open(path, "rb") as handle:
            return handle.read()
    except OSError:
        return None


def lyndon_header() -> str:
    """The palettes as a C table, for the one app that is not Python.

    A header rather than a stylesheet, because the choice of theme has to be
    made at runtime from a setting and GTK's CSS cannot select between eight
    blocks of `@define-color`. So the browser is handed the numbers and emits
    the block for whichever theme is in force, which is the same thing
    `housestyle.palette()` does for the Python apps.
    """
    sys.path.insert(0, HERE)
    import theme as theming                                 # noqa: PLC0415

    lines = [
        "/* Generated by house/sync.py from house/theme.py — do not edit.",
        " *",
        " * The house palettes. Lyndon is C and has no Python package to vendor",
        " * theme.py into, so the eight themes are written out here and app.c",
        " * emits the @define-color block for whichever one the configuration",
        " * names. Every number is the same one the Python apps use, which is the",
        " * whole point: Porcelain in the browser is Porcelain in the terminal.",
        " */",
        "",
        "#pragma once",
        "",
        "typedef struct {",
        "  const char *key;        /* what the configuration file stores     */",
        "  const char *name;       /* what the preferences show              */",
        "  const char *blurb;",
        "  gboolean    dark;",
        "  const char *bg;",
        "  const char *fg;",
        "  const char *dim;",
        "  const char *accent;",
        "  const char *on_accent;  /* a label drawn on the accent            */",
        "  const char *glass;",
        "  const char *view;       /* the theme's background, a step lifted  */",
        "  const char *raised;",
        "  const char *floating;",
        "  const char *hairline;",
        "  const char *success;",
        "  const char *warning;",
        "  const char *error;",
        "} LyHouseTheme;",
        "",
        "static const LyHouseTheme LY_HOUSE_THEMES[] = {",
    ]
    for scheme in theming.ordered():
        lift = ((lambda n: theming.shade(scheme.bg, n)) if scheme.dark
                else (lambda n: theming.shade(scheme.bg, -n)))
        hairline = ("rgba(255,255,255,0.11)" if scheme.dark
                    else "rgba(0,0,0,0.11)")
        fields = [
            c_string(scheme.key), c_string(scheme.name), c_string(scheme.blurb),
            "TRUE" if scheme.dark else "FALSE",
            c_string(scheme.bg), c_string(scheme.fg), c_string(scheme.dim),
            c_string(scheme.accent), c_string(theming.on(scheme.accent)),
            c_string(scheme.glass), c_string(lift(0.015)),
            c_string(lift(0.045)), c_string(lift(0.075)),
            c_string(hairline),
            c_string(scheme.ansi[2] if scheme.dark else scheme.ansi[10]),
            c_string(scheme.ansi[3] if scheme.dark else scheme.ansi[11]),
            c_string(scheme.ansi[1] if scheme.dark else scheme.ansi[9]),
        ]
        lines.append("  { " + ", ".join(fields) + " },")
    lines += [
        "};",
        "",
        "#define LY_HOUSE_THEME_N G_N_ELEMENTS (LY_HOUSE_THEMES)",
        "",
        f"#define LY_HOUSE_DARK_DEFAULT  {c_string(theming.DARK_DEFAULT)}",
        f"#define LY_HOUSE_LIGHT_DEFAULT {c_string(theming.LIGHT_DEFAULT)}",
        "",
    ]
    return "\n".join(lines)


def c_string(text: str) -> str:
    """A Python string as a C one. The blurbs contain apostrophes, not much else."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="report drift and change nothing")
    parser.add_argument("--list", action="store_true",
                        help="print the files and where they go")
    args = parser.parse_args(argv)

    jobs = list(targets())
    header_path = os.path.join(ROOT, LYNDON_HEADER)
    if args.list:
        for source, destination in jobs:
            print(os.path.relpath(destination, ROOT))
        print(LYNDON_HEADER)
        return 0

    stale = []
    for source, destination in jobs:
        wanted = read(source)
        if wanted is None:
            print(f"missing source: {source}", file=sys.stderr)
            return 2
        if read(destination) != wanted:
            stale.append((destination, wanted))

    wanted_header = lyndon_header().encode("utf-8")
    if read(header_path) != wanted_header:
        stale.append((header_path, wanted_header))

    if args.check:
        for destination, _ in stale:
            print(f"stale: {os.path.relpath(destination, ROOT)}")
        if stale:
            print(f"\n{len(stale)} file(s) out of step — run: python3 house/sync.py")
        return 1 if stale else 0

    for destination, wanted in stale:
        os.makedirs(os.path.dirname(destination), exist_ok=True)
        with open(destination, "wb") as handle:
            handle.write(wanted)
        print(f"wrote {os.path.relpath(destination, ROOT)}")
    if not stale:
        print("every app already has the house style")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
